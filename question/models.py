from django.db import models
from django.utils import timezone

from employee.models import Employee

from topic.models import Topic


class Question(models.Model):
    """
    Question model represents interview questions used in candidate evaluation forms.

    This model stores all information about questions including their text, difficulty level,
    source, usage statistics, and relationships to topics and authors.
    """

    # Constant used to calculate maximum score based on difficulty level
    SCORE_MULTIPLIER = 3

    class QuestionDifficulty(models.IntegerChoices):
        """
        Enumeration of question difficulty levels with corresponding numeric values.
        Used for scoring and filtering questions.
        """

        EASY = 1, "Easy"  # Easiest difficulty level, worth 3 points
        MEDIUM = 2, "Medium"  # Medium difficulty level, worth 6 points
        HARD = 3, "Hard"  # Hardest difficulty level, worth 9 points

    class QuestionSource(models.TextChoices):
        """
        Enumeration of possible sources for questions, indicating how they were created.
        Used for tracking question origin and filtering.
        """

        TEMPLATE = "template", "From Template"  # Question from a predefined template
        MANUAL = (
            "added",
            "Added by Interviewer",
        )  # Question manually added by an interviewer
        CHANGED = (
            "changed",
            "Modified by Interviewer",
        )  # Question modified from an existing one
        GENERATED = "generated", "Generated by AI"  # Question generated by AI

    # The actual text content of the question
    question_text = models.TextField()

    # Difficulty level of the question, affects scoring
    difficulty = models.IntegerField(
        choices=QuestionDifficulty.choices,
        default=QuestionDifficulty.EASY,
    )

    # Origin of the question (template, manual, etc.)
    source = models.CharField(
        max_length=25,
        choices=QuestionSource.choices,
        default=QuestionSource.TEMPLATE,
    )

    # Timestamp when the question was last used in an evaluation
    last_used_at = models.DateTimeField(default=timezone.now)

    # Flag indicating if the question is available for use (soft delete mechanism)
    is_active = models.BooleanField(default=True)

    # Topic that this question belongs to
    topic = models.ForeignKey(
        Topic,
        on_delete=models.PROTECT,  # Prevent deletion of topics that have questions
        related_name="questions",  # Access questions from topic via topic.questions
    )

    # Employee who created or last modified the question
    question_author = models.ForeignKey(
        Employee,
        on_delete=models.SET_NULL,  # Set to NULL if the employee is deleted
        related_name="questions",  # Access questions from employee via employee.questions
        null=True,
        blank=True,  # Optional field
    )

    # Counter tracking how many times this question has been used
    usage_count = models.PositiveIntegerField(default=0)

    # Timestamp when the question was created
    created_at = models.DateTimeField(auto_now_add=True)

    # Timestamp when the question was last updated
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "Question"
        verbose_name_plural = "Questions"
        ordering = ("topic", "-usage_count", "created_at")

    @property
    def max_score(self):
        """
        Calculate the maximum possible score for this question based on its difficulty.

        Returns:
            int: The maximum score calculated as difficulty level multiplied by SCORE_MULTIPLIER.
                 Easy questions: 3 points, Medium questions: 6 points, Hard questions: 9 points.
        """
        return self.difficulty * self.SCORE_MULTIPLIER

    def increment_usage(self):
        """
        Increment the usage count of this question and save the change.

        This method is called when the question is used in an evaluation form.
        Only updates the usage_count field to minimize database operations.
        """
        self.usage_count += 1
        self.save(update_fields=["usage_count"])

    def __str__(self):
        """
        Return a string representation of the question, truncating if too long.

        Returns:
            str: The question text, truncated to 75 characters with ellipsis if longer.
        """
        if len(self.question_text) > 75:
            return f"{self.question_text[:75]}..."
        return self.question_text
