from rest_framework import routers
from django.urls import path, include
from question.views import QuestionViewSet


# Define the app namespace for URL reversing
app_name = "question"

# Create a DRF router for automatic URL generation
router = routers.DefaultRouter()

# Register the QuestionViewSet with an empty prefix to make it available at the root of the app's URL
# This creates all the standard REST endpoints (list, create, retrieve, update, delete)
router.register("", QuestionViewSet, basename="question")

# Define the URL patterns for the question app
# Include all the URLs generated by the router
urlpatterns = [path("", include(router.urls))]
